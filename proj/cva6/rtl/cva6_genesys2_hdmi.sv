module cva6_genesys2_hdmi #(
    parameter integer UART_BAUD = 3000000
) (
    input  logic        sys_clk_p,
    input  logic        sys_clk_n,
    input  logic        cpu_resetn,
    inout  wire [31:0]  ddr3_dq,
    inout  wire [3:0]   ddr3_dqs_n,
    inout  wire [3:0]   ddr3_dqs_p,
    output logic [14:0] ddr3_addr,
    output logic [2:0]  ddr3_ba,
    output logic        ddr3_ras_n,
    output logic        ddr3_cas_n,
    output logic        ddr3_we_n,
    output logic        ddr3_reset_n,
    output logic [0:0]  ddr3_ck_p,
    output logic [0:0]  ddr3_ck_n,
    output logic [0:0]  ddr3_cke,
    output logic [0:0]  ddr3_cs_n,
    output logic [3:0]  ddr3_dm,
    output logic [0:0]  ddr3_odt,
    output wire         eth_rst_n,
    input  wire         eth_rxck,
    input  wire         eth_rxctl,
    input  wire [3:0]   eth_rxd,
    output wire         eth_txck,
    output wire         eth_txctl,
    output wire [3:0]   eth_txd,
    inout  wire         eth_mdio,
    output logic        eth_mdc,
    output logic [7:0]  led,
    input  logic [7:0]  sw,
    output logic        fan_pwm,
    input  logic        trst_n,
    output logic        spi_mosi,
    input  logic        spi_miso,
    output logic        spi_ss,
    output logic        spi_clk_o,
    input  logic        tck,
    input  logic        tms,
    input  logic        tdi,
    output wire         tdo,
    input  logic        prog_clko,
    input  logic        prog_rxen,
    input  logic        prog_txen,
    input  logic        prog_spien,
    output logic        prog_rdn,
    output logic        prog_wrn,
    output logic        prog_oen,
    output logic        prog_siwun,
    inout  logic [7:0]  prog_d,
    input  logic        rx,
    output logic        tx,
    output wire         hdmi_out_clk_p,
    output wire         hdmi_out_clk_n,
    output wire [2:0]   hdmi_out_data_p,
    output wire [2:0]   hdmi_out_data_n
);

    logic software_video_ready;
    logic software_video_command_ack;
    logic [31:0] soc_gpio;
    wire [7:0] soc_sw = {sw[7], software_video_ready,
                         software_video_command_ack, sw[4:0]};
    assign led = soc_gpio[7:0];

    ariane_xilinx i_soc (
        .sys_clk_p,
        .sys_clk_n,
        .cpu_resetn,
        .ddr3_dq,
        .ddr3_dqs_n,
        .ddr3_dqs_p,
        .ddr3_addr,
        .ddr3_ba,
        .ddr3_ras_n,
        .ddr3_cas_n,
        .ddr3_we_n,
        .ddr3_reset_n,
        .ddr3_ck_p,
        .ddr3_ck_n,
        .ddr3_cke,
        .ddr3_cs_n,
        .ddr3_dm,
        .ddr3_odt,
        .eth_rst_n,
        .eth_rxck,
        .eth_rxctl,
        .eth_rxd,
        .eth_txck,
        .eth_txctl,
        .eth_txd,
        .eth_mdio,
        .eth_mdc,
        .led(soc_gpio),
        .sw(soc_sw),
        .fan_pwm,
        .trst_n,
        .spi_mosi,
        .spi_miso,
        .spi_ss,
        .spi_clk_o,
        .tck,
        .tms,
        .tdi,
        .tdo,
        .prog_clko,
        .prog_rxen,
        .prog_txen,
        .prog_spien,
        .prog_rdn,
        .prog_wrn,
        .prog_oen,
        .prog_siwun,
        .prog_d,
        .rx,
        .tx
    );

    // CVA6's Genesys 2 MIG exposes a stable 200 MHz UI clock after DDR reset. Tapping it
    // here avoids placing a second input buffer on the board clock pins.
    uart_hdmi_terminal #(
        .UART_BAUD(UART_BAUD)
    ) i_terminal (
        .clk_200(i_soc.ddr_clock_out),
        .reset(~cpu_resetn | i_soc.ddr_sync_reset),
        .uart_tx(tx),
        .software_video_bus(soc_gpio),
        .force_terminal(sw[7]),
        .software_video_ready,
        .software_video_command_ack,
        .hdmi_clk_p(hdmi_out_clk_p),
        .hdmi_clk_n(hdmi_out_clk_n),
        .hdmi_data_p(hdmi_out_data_p),
        .hdmi_data_n(hdmi_out_data_n)
    );

endmodule
